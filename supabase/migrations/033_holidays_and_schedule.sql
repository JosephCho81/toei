-- ─────────────────────────────────────────
-- 1. 대한민국 공휴일 (holidays)
--    정산 예정일이 휴일이면 직전 영업일로 당기기 위한 기준 데이터.
--    임시공휴일·대체공휴일은 관보로 수시 지정되므로 담당자가 직접 추가/삭제할 수 있어야 한다.
-- ─────────────────────────────────────────
CREATE TABLE IF NOT EXISTS holidays (
  date        date PRIMARY KEY,
  name        text NOT NULL,
  is_verified boolean NOT NULL DEFAULT false,  -- 관보/공공데이터 대조 완료 여부
  created_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE holidays ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "everyone can read holidays" ON holidays;
CREATE POLICY "everyone can read holidays"
  ON holidays FOR SELECT USING (true);

DROP POLICY IF EXISTS "authenticated can write holidays" ON holidays;
CREATE POLICY "authenticated can write holidays"
  ON holidays FOR ALL TO authenticated USING (true) WITH CHECK (true);

